import { mkdir, readFile, unlink, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import StyleDictionary from 'style-dictionary'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')
const cssDir = join(root, 'css')

async function buildTheme({ name, sources, selector }) {
  const dest = `_${name}.css`
  const sd = new StyleDictionary({
    source: sources,
    platforms: {
      css: {
        transformGroup: 'css',
        prefix: 'pond',
        buildPath: 'css/',
        files: [
          {
            destination: dest,
            format: 'css/variables',
            options: {
              selector,
              outputReferences: false
            }
          }
        ]
      }
    },
    log: { verbosity: 'verbose' }
  })

  await sd.hasInitialized
  await sd.buildAllPlatforms()
  const css = await readFile(join(cssDir, dest), 'utf8')
  await unlink(join(cssDir, dest)).catch(() => {})
  return css.trim()
}

await mkdir(cssDir, { recursive: true })

const light = await buildTheme({
  name: 'light',
  sources: ['tokens/core.json', 'tokens/semantic.light.json'],
  selector: ':root, [data-theme="light"]'
})

const dark = await buildTheme({
  name: 'dark',
  sources: ['tokens/core.json', 'tokens/semantic.dark.json'],
  selector: '[data-theme="dark"]'
})

const focusBlock = `
/* Shared focus ring — required by a11y DoD */
:where(.pond-focus-ring):focus-visible,
:where(:focus-visible).pond-focus-ring {
  outline: var(--pond-focus-width) solid var(--pond-color-focus-ring);
  outline-offset: var(--pond-focus-offset);
}

@media (prefers-reduced-motion: reduce) {
  :root,
  [data-theme="light"],
  [data-theme="dark"] {
    --pond-motion-duration-fast: 0ms;
    --pond-motion-duration-normal: 0ms;
    --pond-motion-duration-slow: 0ms;
  }
}
`

const plain = `/* Generated by @pond/tokens — do not edit by hand */

${light}

${dark}
${focusBlock}
`

const outFile = join(cssDir, 'plain.css')
await writeFile(outFile, plain, 'utf8')
console.log(`Wrote ${outFile}`)
